public class Relational{
    public static void main(String[] args){
        int x=20;
        int y=15;

        System.out.println("x is " + x + " and y is " + y);

        System.out.println(x>y);
        System.out.println(x<y);
        System.out.println(x==y);
        System.out.println(x!=y);
    }
}