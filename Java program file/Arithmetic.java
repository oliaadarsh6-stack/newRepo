public class Arithmetic {
    public static void main(String[] args) {
        int x=20;
        int y=5;

        System.out.println("x+y = "+(x+y));
        System.out.println("x-y = "+(x-y));
        System.out.println("x*y = "+(x*y));
        System.out.println("x/y = "+(x/y));
        System.out.println("x%y = "+(x%y));
    }
}